-- Portable DDL: runs unchanged on H2 (local/test) and PostgreSQL.

CREATE TABLE links (
    code             VARCHAR(32)              NOT NULL,
    original_url     VARCHAR(2048)            NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    click_count      BIGINT DEFAULT 0         NOT NULL,
    last_accessed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_links PRIMARY KEY (code)
);

-- Append-only click log. It stores the referrer host only: no IP address,
-- no user agent, no full referrer URL.
CREATE TABLE click_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    link_code     VARCHAR(32)              NOT NULL,
    clicked_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    click_day     DATE                     NOT NULL,
    referrer_host VARCHAR(255),
    CONSTRAINT pk_click_events PRIMARY KEY (id),
    CONSTRAINT fk_click_events_link FOREIGN KEY (link_code)
        REFERENCES links (code) ON DELETE CASCADE
);

CREATE INDEX idx_click_events_link_day ON click_events (link_code, click_day);
